from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import copy, get
import os


class SlangRecipe(ConanFile):
    """Slang shader compiler, packaged from the official release binaries.

    Building Slang from source takes long and pulls in LLVM, and ConanCenter has no recipe for it. Only the
    compilation library is used, by a build tool: the binaries are the same for every compiler and build type.
    """
    name = "slang"
    version = "2026.22"
    package_type = "shared-library"
    license = "Apache-2.0 WITH LLVM-exception"
    url = "https://github.com/shader-slang/slang"

    settings = "os", "arch", "compiler", "build_type"

    def validate(self):
        if self.settings.os not in ("Windows", "Linux") or self.settings.arch != "x86_64":
            raise ConanInvalidConfiguration(
                f"slang binaries are only packaged for Windows and Linux x86_64, not {self.settings.os} {self.settings.arch}"
            )

    def package_id(self):
        # Prebuilt binaries: they don't depend on the compiler or build type of the consumer
        del self.info.settings.compiler
        del self.info.settings.build_type

    def build(self):
        # Downloaded in build() rather than source(), as the archive depends on the OS. Its files have no root folder.
        get(self, **self.conan_data["sources"][self.version][str(self.settings.os)])

    def package(self):
        copy(self, "LICENSE", self.build_folder, os.path.join(self.package_folder, "licenses"))
        copy(self, "*", os.path.join(self.build_folder, "LICENSES"), os.path.join(self.package_folder, "licenses"))
        copy(self, "*", os.path.join(self.build_folder, "third-party-notices"),
             os.path.join(self.package_folder, "licenses", "third-party-notices"))
        copy(self, "*.h", os.path.join(self.build_folder, "include"), os.path.join(self.package_folder, "include"))
        # The shared libraries load the standard modules (slang-standard-module-<version>/) and the libraries of
        # optional features (e.g. slang-glslang) from their own folder: bin/ on Windows, lib/ on Linux. Both folders
        # are copied whole, except the CMake and pkg-config files, which Conan generates instead.
        copy(self, "*", os.path.join(self.build_folder, "bin"), os.path.join(self.package_folder, "bin"))
        copy(self, "*", os.path.join(self.build_folder, "lib"), os.path.join(self.package_folder, "lib"),
             excludes=("cmake/*", "pkgconfig/*"))

    def package_info(self):
        # Targets generated by Conan rather than the shipped slangConfig.cmake, which refers to a slang-llvm.dll that
        # the Windows release doesn't contain. As a shared library target, its DLL is listed by $<TARGET_RUNTIME_DLLS>.
        self.cpp_info.set_property("cmake_file_name", "slang")
        self.cpp_info.set_property("cmake_target_name", "slang::slang")
        self.cpp_info.libs = ["slang-compiler"]
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libdirs = ["lib"]
